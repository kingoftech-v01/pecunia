class AIAnalysisCache(models.Model):
    """
    Cache for AI analysis results.

    Stores analysis results to reduce API calls for repeated queries.
    """
    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)
    user = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        on_delete=models.CASCADE,
        related_name='ai_analysis_cache'
    )

    # Cache key
    analysis_type = models.CharField(max_length=50)
    cache_key = models.CharField(max_length=255)

    # Cached data
    result = models.JSONField()

    # Expiration
    created_at = models.DateTimeField(auto_now_add=True)
    expires_at = models.DateTimeField()

    class Meta:
        verbose_name = 'AI analysis cache'
        verbose_name_plural = 'AI analysis cache entries'
        unique_together = ['user', 'analysis_type', 'cache_key']
        indexes = [
            models.Index(fields=['user', 'analysis_type', 'cache_key']),
            models.Index(fields=['expires_at']),
        ]

    def __str__(self):
        return f"{self.analysis_type}: {self.cache_key}"

    @property
    def is_expired(self):
        """Check if cache entry has expired."""
        from django.utils import timezone
        return timezone.now() > self.expires_at


class AIConversation(models.Model):
    """
    AI conversation history with users.

    Stores the full conversation thread and context
    for the AI assistant feature.
    """
    id = models.UUIDField(
        primary_key=True,
        default=uuid.uuid4,
        editable=False,
        help_text="Unique identifier for the conversation"
    )
    user = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        on_delete=models.CASCADE,
        related_name='ai_conversations',
        help_text="User who owns this conversation"
    )
    title = models.CharField(
        max_length=255,
        blank=True,
        default='',
        help_text="Optional title for the conversation"
    )
    messages = models.JSONField(
        default=list,
        help_text="List of messages in the conversation [{role, content, timestamp}]"
    )
    context = models.JSONField(
        default=dict,
        blank=True,
        help_text="Conversation context (user preferences, relevant data, etc.)"
    )
    is_active = models.BooleanField(
        default=True,
        db_index=True,
        help_text="Whether the conversation is still active"
    )
    created_at = models.DateTimeField(
        auto_now_add=True,
        help_text="When this conversation started"
    )
    updated_at = models.DateTimeField(
        auto_now=True,
        help_text="When this conversation was last updated"
    )

    class Meta:
        db_table = 'ai_conversations'
        ordering = ['-updated_at']
        indexes = [
            models.Index(fields=['user', 'is_active', '-updated_at']),
        ]
        verbose_name = 'AI Conversation'
        verbose_name_plural = 'AI Conversations'

    def __str__(self):
        return f"Conversation {self.id} - {self.user}"

    def add_message(self, role: str, content: str):
        """
        Add a message to the conversation.

        Args:
            role: 'user' or 'assistant'
            content: Message content
        """
        from django.utils import timezone

        message = {
            'role': role,
            'content': content,
            'timestamp': timezone.now().isoformat()
        }
        self.messages.append(message)
        self.save(update_fields=['messages', 'updated_at'])

    def get_messages_for_api(self):
        """
        Get messages formatted for the Claude API.

        Returns:
            List of messages with 'role' and 'content' keys
        """
        return [
            {'role': msg['role'], 'content': msg['content']}
            for msg in self.messages
        ]

    def clear_messages(self):
        """Clear all messages from the conversation."""
        self.messages = []
        self.save(update_fields=['messages', 'updated_at'])


