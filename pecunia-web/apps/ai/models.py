"""
AI Models.

Data models for AI-generated insights, recommendations, conversations, and usage tracking.
"""
import uuid
from decimal import Decimal
from django.db import models
from django.conf import settings
from django.core.validators import MinValueValidator, MaxValueValidator


class AIRecommendation(models.Model):
    """
    AI-generated recommendation model.

    Stores personalized financial recommendations and insights
    generated by Claude AI.
    """
    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)
    user = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        on_delete=models.CASCADE,
        related_name='ai_recommendations'
    )

    # Recommendation type
    class RecommendationType(models.TextChoices):
        BUDGET_ALERT = 'budget_alert', 'Budget Alert'
        SPENDING_INSIGHT = 'spending_insight', 'Spending Insight'
        SAVING_TIP = 'saving_tip', 'Saving Tip'
        ANOMALY = 'anomaly', 'Anomaly Detection'

    type = models.CharField(
        max_length=50,
        choices=RecommendationType.choices,
        db_index=True,
        help_text="Type of recommendation"
    )

    # Content
    title = models.CharField(max_length=255)
    content = models.TextField()

    # Priority for display ordering (1-5 scale)
    PRIORITY_MAP = {
        'low': 1,
        'medium': 2,
        'high': 3,
        'urgent': 4,
        'critical': 5,
    }

    priority = models.PositiveSmallIntegerField(
        validators=[MinValueValidator(1), MaxValueValidator(5)],
        default=3,
        db_index=True,
        help_text="Priority level (1=lowest, 5=highest)"
    )

    @classmethod
    def normalize_priority(cls, value):
        """Convert string priority to integer if needed."""
        if isinstance(value, str):
            return cls.PRIORITY_MAP.get(value.lower(), 3)
        if isinstance(value, int) and 1 <= value <= 5:
            return value
        return 3

    # Status
    is_read = models.BooleanField(default=False)
    is_dismissed = models.BooleanField(default=False)
    is_actionable = models.BooleanField(default=True)

    # Metadata
    metadata = models.JSONField(default=dict, blank=True)
    confidence_score = models.FloatField(null=True, blank=True)

    # Related entities (optional)
    related_transaction = models.ForeignKey(
        'transactions.Transaction',
        on_delete=models.SET_NULL,
        null=True,
        blank=True,
        related_name='ai_recommendations'
    )
    related_category = models.ForeignKey(
        'transactions.TransactionCategory',
        on_delete=models.SET_NULL,
        null=True,
        blank=True,
        related_name='ai_recommendations'
    )

    # Timestamps
    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)
    expires_at = models.DateTimeField(null=True, blank=True)

    class Meta:
        verbose_name = 'AI recommendation'
        verbose_name_plural = 'AI recommendations'
        ordering = ['-created_at']
        indexes = [
            models.Index(fields=['user', 'is_read']),
            models.Index(fields=['user', 'type']),
            models.Index(fields=['user', 'priority']),
            models.Index(fields=['user', 'created_at']),
        ]

    def __str__(self):
        return f"{self.title} ({self.type})"

    def mark_as_read(self):
        """Mark the recommendation as read."""
        if not self.is_read:
            self.is_read = True
            self.save(update_fields=['is_read', 'updated_at'])

    def dismiss(self):
        """Dismiss the recommendation."""
        self.is_dismissed = True
        self.save(update_fields=['is_dismissed', 'updated_at'])


