class AIUsageLog(models.Model):
    """
    AI API usage logging for cost tracking.

    Tracks every API call to Claude for monitoring
    usage patterns and costs.
    """

    class ModelType(models.TextChoices):
        CLAUDE_3_OPUS = 'claude-3-opus-20240229', 'Claude 3 Opus'
        CLAUDE_3_SONNET = 'claude-3-sonnet-20240229', 'Claude 3 Sonnet'
        CLAUDE_3_HAIKU = 'claude-3-haiku-20240307', 'Claude 3 Haiku'
        CLAUDE_35_SONNET = 'claude-3-5-sonnet-20241022', 'Claude 3.5 Sonnet'
        CLAUDE_35_HAIKU = 'claude-3-5-haiku-20241022', 'Claude 3.5 Haiku'
        CLAUDE_4_OPUS = 'claude-opus-4-5-20251101', 'Claude Opus 4.5'

    class EndpointType(models.TextChoices):
        CHAT = 'chat', 'Chat'
        CATEGORIZE = 'categorize', 'Categorize'
        ANALYZE = 'analyze', 'Analyze Spending'
        RECOMMEND = 'recommend', 'Generate Recommendations'

    # Pricing per 1M tokens (as of late 2024)
    PRICING = {
        'claude-3-opus-20240229': {'input': 15.00, 'output': 75.00},
        'claude-3-sonnet-20240229': {'input': 3.00, 'output': 15.00},
        'claude-3-haiku-20240307': {'input': 0.25, 'output': 1.25},
        'claude-3-5-sonnet-20241022': {'input': 3.00, 'output': 15.00},
        'claude-3-5-haiku-20241022': {'input': 0.80, 'output': 4.00},
        'claude-opus-4-5-20251101': {'input': 15.00, 'output': 75.00},
    }

    id = models.UUIDField(
        primary_key=True,
        default=uuid.uuid4,
        editable=False,
        help_text="Unique identifier for the log entry"
    )
    user = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        on_delete=models.CASCADE,
        related_name='ai_usage_logs',
        help_text="User who made this API call"
    )
    model = models.CharField(
        max_length=50,
        choices=ModelType.choices,
        db_index=True,
        help_text="AI model used"
    )
    tokens_input = models.PositiveIntegerField(
        default=0,
        help_text="Number of input tokens"
    )
    tokens_output = models.PositiveIntegerField(
        default=0,
        help_text="Number of output tokens"
    )
    cost_estimate = models.DecimalField(
        max_digits=10,
        decimal_places=6,
        default=0,
        help_text="Estimated cost in USD"
    )
    endpoint = models.CharField(
        max_length=20,
        choices=EndpointType.choices,
        db_index=True,
        help_text="API endpoint/feature used"
    )
    request_id = models.CharField(
        max_length=100,
        blank=True,
        default='',
        help_text="Claude API request ID for debugging"
    )
    latency_ms = models.PositiveIntegerField(
        null=True,
        blank=True,
        help_text="API call latency in milliseconds"
    )
    success = models.BooleanField(
        default=True,
        db_index=True,
        help_text="Whether the API call was successful"
    )
    error_message = models.TextField(
        blank=True,
        default='',
        help_text="Error message if the call failed"
    )
    created_at = models.DateTimeField(
        auto_now_add=True,
        db_index=True,
        help_text="When this API call was made"
    )

    class Meta:
        db_table = 'ai_usage_logs'
        ordering = ['-created_at']
        indexes = [
            models.Index(fields=['user', 'created_at']),
            models.Index(fields=['model', 'endpoint', 'created_at']),
        ]
        verbose_name = 'AI Usage Log'
        verbose_name_plural = 'AI Usage Logs'

    def __str__(self):
        return f"{self.endpoint} - {self.model} ({self.tokens_input + self.tokens_output} tokens)"

    def save(self, *args, **kwargs):
        """Calculate cost estimate before saving."""
        if self.model in self.PRICING:
            pricing = self.PRICING[self.model]
            input_cost = (self.tokens_input / 1_000_000) * pricing['input']
            output_cost = (self.tokens_output / 1_000_000) * pricing['output']
            self.cost_estimate = Decimal(str(input_cost + output_cost))
        super().save(*args, **kwargs)

    @classmethod
    def get_user_usage_stats(cls, user, days=30):
        """
        Get usage statistics for a user.

        Args:
            user: User instance
            days: Number of days to look back

        Returns:
            Dictionary with usage statistics
        """
        from django.utils import timezone
        from django.db.models import Sum, Count, Avg
        from datetime import timedelta

        start_date = timezone.now() - timedelta(days=days)

        stats = cls.objects.filter(
            user=user,
            created_at__gte=start_date,
            success=True
        ).aggregate(
            total_calls=Count('id'),
            total_input_tokens=Sum('tokens_input'),
            total_output_tokens=Sum('tokens_output'),
            total_cost=Sum('cost_estimate'),
            avg_latency=Avg('latency_ms')
        )

        return {
            'total_calls': stats['total_calls'] or 0,
            'total_input_tokens': stats['total_input_tokens'] or 0,
            'total_output_tokens': stats['total_output_tokens'] or 0,
            'total_tokens': (stats['total_input_tokens'] or 0) + (stats['total_output_tokens'] or 0),
            'total_cost': float(stats['total_cost'] or 0),
            'avg_latency_ms': stats['avg_latency'] or 0,
            'period_days': days
        }
