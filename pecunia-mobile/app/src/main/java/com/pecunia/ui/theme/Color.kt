// ============================================
// Budget Status Colors
// ============================================
object BudgetColors {
    val onTrack = Color(0xFF2E7D32)        // Under 80%
    val warning = Color(0xFFFF9800)         // 80-100%
    val overBudget = Color(0xFFEF5350)      // Over 100%
    val unused = Color(0xFF9E9E9E)          // No spending
    val safe = BudgetSafe
    val danger = BudgetDanger
    val exceeded = BudgetExceeded

    fun getStatusColor(percentage: Float): Color {
        return when {
            percentage <= 0f -> unused
            percentage < 0.8f -> onTrack
            percentage <= 1f -> warning
            else -> overBudget
        }
    }

    fun getProgressColor(spent: Double, budget: Double): Color {
        if (budget <= 0) return unused
        val percentage = (spent / budget).toFloat()
        return getStatusColor(percentage)
    }
}

// ============================================
// Goal Progress Colors
// ============================================
object GoalColors {
    val notStarted = Color(0xFF9E9E9E)
    val inProgress = Color(0xFF1A5F7A)
    val almostThere = Color(0xFFFF9800)
    val completed = Color(0xFF2E7D32)
    val overdue = Color(0xFFEF5350)

    fun getProgressColor(percentage: Float): Color {
        return when {
            percentage <= 0f -> notStarted
            percentage < 0.75f -> inProgress
            percentage < 1f -> almostThere
            else -> completed
        }
    }

    fun getStatusColor(current: Double, target: Double, isOverdue: Boolean = false): Color {
        if (isOverdue && current < target) return overdue
        if (target <= 0) return notStarted
        val percentage = (current / target).toFloat()
        return getProgressColor(percentage)
    }
}

